CREATE TABLE transfer_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id) ON DELETE RESTRICT,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    direction VARCHAR(6) NOT NULL CHECK (direction IN ('DEBIT', 'CREDIT')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    sequence_number INTEGER NOT NULL CHECK (sequence_number > 0),
    UNIQUE (transfer_id, sequence_number)
);

CREATE INDEX ix_transfer_postings_transfer_account
    ON transfer_postings(transfer_id, account_id);

INSERT INTO transfer_postings(transfer_id, account_id, direction, amount_paise, sequence_number)
SELECT transfer_id,
             account_id,
             direction,
             amount_paise,
             ROW_NUMBER() OVER (PARTITION BY transfer_id ORDER BY id)::INTEGER
    FROM ledger_entries;

CREATE TRIGGER trg_transfer_postings_immutable
    BEFORE UPDATE OR DELETE ON transfer_postings
    FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();

ALTER TABLE transfer_status_audit
    ADD COLUMN reason VARCHAR(500);

CREATE OR REPLACE FUNCTION audit_transfer_status() RETURNS TRIGGER AS $$
DECLARE
    actor_id BIGINT;
    actor_label VARCHAR(80);
    change_reason VARCHAR(500);
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status THEN
        RETURN NEW;
    END IF;

    actor_id := NULLIF(current_setting('app.actor_user_id', TRUE), '')::BIGINT;
    actor_label := COALESCE(
        NULLIF(current_setting('app.actor_label', TRUE), ''),
        CASE WHEN actor_id IS NULL THEN 'SYSTEM' ELSE 'USER' END);
    change_reason := NULLIF(current_setting('app.status_change_reason', TRUE), '');

    INSERT INTO transfer_status_audit(
        transfer_id, old_status, new_status, changed_by_user_id, changed_by_label, reason
    ) VALUES (
        NEW.id,
        CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
        NEW.status,
        actor_id,
        actor_label,
        change_reason
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

