CREATE FUNCTION apply_ledger_balance() RETURNS TRIGGER AS $$
BEGIN
    UPDATE accounts
       SET balance_paise = balance_paise +
           CASE NEW.direction WHEN 'CREDIT' THEN NEW.amount_paise ELSE -NEW.amount_paise END
     WHERE id = NEW.account_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ledger_apply_balance
    AFTER INSERT ON ledger_entries
    FOR EACH ROW EXECUTE FUNCTION apply_ledger_balance();

CREATE FUNCTION reject_ledger_mutation() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'ledger entries are append-only'
        USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ledger_entries_immutable
    BEFORE UPDATE OR DELETE ON ledger_entries
    FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();

CREATE FUNCTION assert_completed_transfer_balanced() RETURNS TRIGGER AS $$
DECLARE
    transfer_id_to_check BIGINT;
    expected_amount BIGINT;
    current_status VARCHAR(24);
    debit_total NUMERIC;
    credit_total NUMERIC;
    entry_count BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'transfers' THEN
        transfer_id_to_check := NEW.id;
    ELSE
        transfer_id_to_check := NEW.transfer_id;
    END IF;

    SELECT amount_paise, status
      INTO expected_amount, current_status
      FROM transfers
     WHERE id = transfer_id_to_check;

    IF current_status IS DISTINCT FROM 'COMPLETED' THEN
        RETURN NULL;
    END IF;

    SELECT COALESCE(SUM(amount_paise) FILTER (WHERE direction = 'DEBIT'), 0),
           COALESCE(SUM(amount_paise) FILTER (WHERE direction = 'CREDIT'), 0),
           COUNT(*)
      INTO debit_total, credit_total, entry_count
      FROM ledger_entries
     WHERE transfer_id = transfer_id_to_check;

    IF entry_count < 2 OR debit_total <> expected_amount OR credit_total <> expected_amount THEN
        RAISE EXCEPTION 'completed transfer % is not balanced', transfer_id_to_check
            USING ERRCODE = '23514';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_completed_transfer_balanced
    AFTER INSERT OR UPDATE ON transfers
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_completed_transfer_balanced();

CREATE CONSTRAINT TRIGGER trg_ledger_transfer_balanced
    AFTER INSERT ON ledger_entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_completed_transfer_balanced();

CREATE FUNCTION audit_transfer_status() RETURNS TRIGGER AS $$
DECLARE
    actor_id BIGINT;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status THEN
        RETURN NEW;
    END IF;

    actor_id := NULLIF(current_setting('app.actor_user_id', TRUE), '')::BIGINT;

    INSERT INTO transfer_status_audit(
        transfer_id, old_status, new_status, changed_by_user_id, changed_by_label
    ) VALUES (
        NEW.id,
        CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
        NEW.status,
        actor_id,
        CASE WHEN actor_id IS NULL THEN 'SYSTEM' ELSE 'USER' END
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfers_status_audit
    AFTER INSERT OR UPDATE ON transfers
    FOR EACH ROW EXECUTE FUNCTION audit_transfer_status();

