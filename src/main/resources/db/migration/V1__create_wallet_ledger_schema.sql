CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    phone VARCHAR(32) NOT NULL UNIQUE,
    kyc_status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    account_type VARCHAR(24) NOT NULL
        CHECK (account_type IN ('USER_WALLET', 'CASH_IN', 'CASH_OUT', 'FEE_REVENUE')),
    account_name VARCHAR(120) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    balance_paise BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((account_type = 'USER_WALLET' AND owner_user_id IS NOT NULL)
        OR (account_type <> 'USER_WALLET' AND owner_user_id IS NULL)),
    CHECK (account_type <> 'USER_WALLET' OR balance_paise >= 0)
);

CREATE UNIQUE INDEX uq_accounts_system_type
    ON accounts(account_type)
    WHERE owner_user_id IS NULL;

CREATE INDEX ix_accounts_owner ON accounts(owner_user_id, id)
    WHERE owner_user_id IS NOT NULL;

CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    initiated_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    transfer_type VARCHAR(24) NOT NULL
        CHECK (transfer_type IN ('TOP_UP', 'PEER_TRANSFER', 'WITHDRAWAL', 'FEE', 'REVERSAL')),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'HELD', 'COMPLETED', 'REJECTED', 'REVERSED')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    reversal_of_transfer_id BIGINT REFERENCES transfers(id) ON DELETE RESTRICT,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((transfer_type = 'REVERSAL' AND reversal_of_transfer_id IS NOT NULL)
        OR (transfer_type <> 'REVERSAL' AND reversal_of_transfer_id IS NULL))
);

CREATE UNIQUE INDEX uq_transfers_single_reversal
    ON transfers(reversal_of_transfer_id)
    WHERE reversal_of_transfer_id IS NOT NULL;

CREATE INDEX ix_transfers_initiator_created
    ON transfers(initiated_by_user_id, created_at DESC, id DESC);

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id) ON DELETE RESTRICT,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    direction VARCHAR(6) NOT NULL CHECK (direction IN ('DEBIT', 'CREDIT')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_ledger_account_statement
    ON ledger_entries(account_id, created_at DESC, id DESC);

CREATE INDEX ix_ledger_transfer ON ledger_entries(transfer_id);

CREATE TABLE idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    idempotency_key UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PROCESSING', 'COMPLETED')),
    response_code INTEGER,
    response_body TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    UNIQUE (user_id, idempotency_key),
    CHECK ((status = 'PROCESSING' AND response_code IS NULL AND response_body IS NULL)
        OR (status = 'COMPLETED' AND response_code IS NOT NULL AND response_body IS NOT NULL))
);

CREATE UNIQUE INDEX uq_idempotency_anonymous_key
    ON idempotency_keys(idempotency_key)
    WHERE user_id IS NULL;

CREATE TABLE transfer_status_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id) ON DELETE RESTRICT,
    old_status VARCHAR(24),
    new_status VARCHAR(24) NOT NULL,
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_by_label VARCHAR(80) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_transfer_status_audit_transfer
    ON transfer_status_audit(transfer_id, changed_at DESC, id DESC);

CREATE TABLE reconciliation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status VARCHAR(16) NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'MISMATCHES', 'FAILED')),
    problem_count INTEGER NOT NULL DEFAULT 0 CHECK (problem_count >= 0),
    details JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE reconciliation_problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES reconciliation_runs(id) ON DELETE RESTRICT,
    check_name VARCHAR(80) NOT NULL,
    entity_id BIGINT,
    expected_value TEXT,
    actual_value TEXT,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_reconciliation_problems_run ON reconciliation_problems(run_id, id);

CREATE TABLE job_locks (
